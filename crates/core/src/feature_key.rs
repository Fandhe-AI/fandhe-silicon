#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn feature_query_keys_has_79_entries() {
        assert_eq!(FEATURE_QUERY_KEYS.len(), 79);
    }

    #[test]
    fn feature_query_keys_are_distinct() {
        for (i, a) in FEATURE_QUERY_KEYS.iter().enumerate() {
            for b in &FEATURE_QUERY_KEYS[i + 1..] {
                assert_ne!(a, b);
            }
        }
    }

    #[test]
    fn feature_query_keys_have_prefix_and_upper_name() {
        for key in FEATURE_QUERY_KEYS {
            let rest = key.0.strip_prefix("feature:").expect("prefix");
            assert!(!rest.is_empty());
            assert!(
                rest.bytes()
                    .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_')
            );
        }
    }

    #[test]
    fn constant_names_match_strings() {
        assert_eq!(FEATURE_QUERY_KEYS[0], FEATURE_SHADER_FLOAT32_ATOMIC);
        assert_eq!(
            FEATURE_QUERY_KEYS.last().copied(),
            Some(FEATURE_PRIMITIVE_INDEX)
        );
        assert_eq!(
            FEATURE_EXPERIMENTAL_COOPERATIVE_MATRIX.0,
            "feature:EXPERIMENTAL_COOPERATIVE_MATRIX"
        );
        assert_eq!(
            FEATURE_RG11B10UFLOAT_RENDERABLE.0,
            "feature:RG11B10UFLOAT_RENDERABLE"
        );
        assert_eq!(
            FEATURE_DEPTH32FLOAT_STENCIL8.0,
            "feature:DEPTH32FLOAT_STENCIL8"
        );
    }
}
